-- Reconstructed logical schema, NOT a byte-for-byte SQL Server restore.
-- Original catalogs UserInfo00..05 / UserInventory00..05 are consolidated.
-- Table/procedure field evidence: LS CDBMan::InitUser/RegisterNewUser;
-- FXGS prGetUserInfo/prUpdateUserDynamic; FXSS prLoadInventory/prAddInventory.
CREATE TABLE FxUserAccount (
  SID INTEGER PRIMARY KEY AUTOINCREMENT CHECK (SID BETWEEN 1 AND 2147483647),
  ID TEXT NOT NULL COLLATE NOCASE UNIQUE,
  UserHashNo INTEGER NOT NULL CHECK (UserHashNo BETWEEN 0 AND 5),
  Password TEXT NOT NULL,
  Name TEXT NOT NULL DEFAULT '',
  Email TEXT NOT NULL DEFAULT '', EmailRcv INTEGER NOT NULL DEFAULT 0,
  Gender INTEGER NOT NULL DEFAULT 0, Address TEXT NOT NULL DEFAULT '',
  Tel TEXT NOT NULL DEFAULT '', Reveal INTEGER NOT NULL DEFAULT 0,
  Profile TEXT NOT NULL DEFAULT '', PasswordQ TEXT NOT NULL DEFAULT '',
  PasswordA TEXT NOT NULL DEFAULT '', IdentityNo TEXT NOT NULL DEFAULT '',
  Birthday TEXT NOT NULL DEFAULT '', CommunitySvr INTEGER NOT NULL DEFAULT 0,
  GuildSn INTEGER NOT NULL DEFAULT 0, Authority INTEGER NOT NULL DEFAULT 0,
  TotalConn INTEGER NOT NULL DEFAULT 0, LastConn INTEGER,
  CreatedAt INTEGER NOT NULL DEFAULT (unixepoch()),
  BannedUntil INTEGER NOT NULL DEFAULT 0
) STRICT;
CREATE TABLE FxUserDynamic (
  ID TEXT PRIMARY KEY COLLATE NOCASE REFERENCES FxUserAccount(ID) ON DELETE CASCADE,
  Money INTEGER NOT NULL DEFAULT 0 CHECK (Money BETWEEN 0 AND 2147483647),
  Exp INTEGER NOT NULL DEFAULT 0 CHECK (Exp BETWEEN 0 AND 2147483647),
  Win INTEGER NOT NULL DEFAULT 0 CHECK (Win BETWEEN 0 AND 2147483647),
  Draw INTEGER NOT NULL DEFAULT 0 CHECK (Draw BETWEEN 0 AND 2147483647),
  Lose INTEGER NOT NULL DEFAULT 0 CHECK (Lose BETWEEN 0 AND 2147483647),
  TicketDate INTEGER NOT NULL DEFAULT 0
) STRICT;
CREATE TABLE FxUserInventory (
  SN INTEGER PRIMARY KEY AUTOINCREMENT CHECK (SN BETWEEN 1 AND 2147483647),
  ID TEXT NOT NULL COLLATE NOCASE REFERENCES FxUserAccount(ID) ON DELETE CASCADE,
  ItemID INTEGER NOT NULL CHECK (ItemID BETWEEN 0 AND 4294967295),
  Slot INTEGER NOT NULL DEFAULT 0 CHECK (Slot BETWEEN 0 AND 255),
  Amount INTEGER NOT NULL CHECK (Amount BETWEEN 1 AND 2147483647),
  ExpireDate INTEGER NOT NULL DEFAULT 0,
  Verbose TEXT NOT NULL DEFAULT '',
  CreatedAt INTEGER NOT NULL DEFAULT (unixepoch())
) STRICT;
CREATE INDEX IX_FxUserInventory_ID ON FxUserInventory(ID);
CREATE TABLE FxPreInventory (
  SN INTEGER PRIMARY KEY AUTOINCREMENT,
  ID TEXT NOT NULL COLLATE NOCASE REFERENCES FxUserAccount(ID) ON DELETE CASCADE,
  ItemID INTEGER NOT NULL, Amount INTEGER NOT NULL CHECK (Amount > 0),
  ValidityPeriod INTEGER NOT NULL DEFAULT 0, Verbose TEXT NOT NULL DEFAULT '',
  CreatedAt INTEGER NOT NULL DEFAULT (unixepoch())
) STRICT;
-- Keep unknown columns explicitly opaque; no invented official shop prices.
CREATE TABLE FxItem (
  ItemID INTEGER PRIMARY KEY CHECK (ItemID BETWEEN 0 AND 4294967295),
  Type INTEGER NOT NULL CHECK (Type BETWEEN 0 AND 255),
  TmplName TEXT NOT NULL, OpaqueColumn3 INTEGER NOT NULL,
  OpaqueColumn4 INTEGER NOT NULL, OpaqueColumn5 INTEGER NOT NULL,
  Verbose TEXT NOT NULL
) STRICT;
CREATE TABLE FxUserOptions (Name TEXT PRIMARY KEY, Value TEXT NOT NULL) STRICT;
CREATE TABLE FxGuildAccount (
  SN INTEGER PRIMARY KEY AUTOINCREMENT,
  Name TEXT NOT NULL COLLATE NOCASE UNIQUE,
  MasterID TEXT NOT NULL COLLATE NOCASE REFERENCES FxUserAccount(ID),
  Profile TEXT NOT NULL DEFAULT '', MarkRevision INTEGER NOT NULL DEFAULT 0,
  CreatedAt INTEGER NOT NULL DEFAULT (unixepoch())
) STRICT;
CREATE TABLE FxGuildDynamic (
  SN INTEGER PRIMARY KEY REFERENCES FxGuildAccount(SN) ON DELETE CASCADE,
  Exp INTEGER NOT NULL DEFAULT 0, Win INTEGER NOT NULL DEFAULT 0,
  Draw INTEGER NOT NULL DEFAULT 0, Lose INTEGER NOT NULL DEFAULT 0
) STRICT;
-- Runtime-only administrative journal, not an official table.
CREATE TABLE RuntimeAudit (
  SN INTEGER PRIMARY KEY AUTOINCREMENT,
  Time INTEGER NOT NULL DEFAULT (unixepoch()),
  Action TEXT NOT NULL, SID INTEGER, Details TEXT NOT NULL
) STRICT;
