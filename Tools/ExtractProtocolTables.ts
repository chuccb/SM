import { writeFileSync, mkdirSync } from "node:fs";
import { CPeImage, OFFICIAL_SERVICES } from "./OfficialSource.ts";

// All lengths and symbols here are IDA declarations, checked against inverse permutations.
const image = new CPeImage(OFFICIAL_SERVICES.LS);
const rows = 16;
const width = 256;
const tables = ["gsConvertTableEncode", "gsConvertTableDecode"].map((name) => {
  const va = image.symbolVA(name);
  return { name, va, bytes: image.read(va, rows * width) };
});
const [encode, decode] = tables;
if (!encode || !decode) throw new Error("Missing tables");
for (let row = 0; row < rows; row++) {
  for (let col = 0; col < width; col++) {
    if (decode.bytes[row * width + encode.bytes[row * width + col]!] !== col)
      throw new Error("Header table inverse mismatch");
  }
}
for (const file of [
  OFFICIAL_SERVICES.Center,
  OFFICIAL_SERVICES.FXGS,
  OFFICIAL_SERVICES.FXSS,
  OFFICIAL_SERVICES.FXUS,
]) {
  const other = new CPeImage(file);
  for (const t of tables) {
    if (!other.read(other.symbolVA(t.name), rows * width).equals(t.bytes))
      throw new Error(
        `${file}: ${t.name} differs; do not silently use another build's tables`,
      );
  }
}
const levelVA = image.symbolVA("g_nLevel2ExpTable");
const sizeVA = image.symbolVA("kLevelTableSize");
const size = image.read(sizeVA, 4).readUInt32LE();
if (size < 2 || size > 1000)
  throw new Error(`Implausible level table size: ${size}`);
const levelBytes = image.read(levelVA, size * 4);
// The gameplay calculator must not silently reuse a different service's table.
const gameImage = new CPeImage(OFFICIAL_SERVICES.FXGS);
const gameLevelVA = gameImage.symbolVA("g_nLevel2ExpTable");
const gameSizeVA = gameImage.symbolVA("kLevelTableSize");
if (
  gameImage.read(gameSizeVA, 4).readUInt32LE() !== size ||
  !gameImage.read(gameLevelVA, size * 4).equals(levelBytes)
)
  throw new Error(
    "LS/FXGS level tables differ; cannot share calculator thresholds",
  );
const levels = Array.from({ length: size }, (_, i) =>
  levelBytes.readInt32LE(i * 4),
);
if (levels.some((v, i) => i > 0 && v < levels[i - 1]!))
  throw new Error("Nonmonotonic level table");
mkdirSync("Common/Protocol", { recursive: true });
let content = `// Generated by Tools/ExtractProtocolTables.ts. Do not edit by hand.\n// Source: ${image.file}, SHA-256 ${image.sha256}\n// Header tables byte-identical across Center, LS, FXGS, FXSS, FXUS.\n`;
for (const t of tables) {
  content += `\n// ${t.name} @ 0x${t.va.toString(16)}, 16 permutations of 256 bytes.\nexport const ${t.name} = [\n`;
  for (let row = 0; row < rows; row++)
    content += `  Buffer.from("${t.bytes.subarray(row * width, (row + 1) * width).toString("hex")}", "hex"),\n`;
  content += "] as const;\n";
}
content += `\n// LS g_nLevel2ExpTable @ 0x${levelVA.toString(16)}; kLevelTableSize @ 0x${sizeVA.toString(16)}.\n// Byte-identical to FXGS @ 0x${gameLevelVA.toString(16)} / 0x${gameSizeVA.toString(16)} (${size} signed DWORDs).\nexport const g_nLevel2ExpTable: readonly number[] = ${JSON.stringify(levels)};\nexport const kLevelTableSize = g_nLevel2ExpTable.length;\n`;
writeFileSync("Common/Protocol/OfficialTables.ts", content);
console.log(
  `Extracted both header tables and ${levels.length} level thresholds from ${image.file}`,
);
